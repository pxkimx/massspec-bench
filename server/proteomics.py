def _tmt_matrix(job, sdir, psm, fdr, S, params, name_to_run):
    """Reporter-ion intensities per peptide (summed over its PSMs). Channels are the samples."""
    tm = pd.read_csv(sdir / "tmt.tsv", sep="\t")
    ch = [c for c in tm.columns if c not in ("filename", "scannr", "ion_injection_time")]
    ok = psm[(~psm["decoy"]) & (psm["peptide_q"] <= fdr)][["filename", "scannr", "peptide", "proteins"]]
    m = ok.merge(tm, on=["filename", "scannr"], how="inner")
    if not len(m):
        job.flag("warn", "No reporter-ion intensities could be matched to identified spectra (check the TMT plex and MS level).")
        return None, [], {}, ""
    agg = m.groupby(["peptide", "proteins"])[ch].sum(min_count=1).reset_index()
    labels = [x.strip() for x in str(params.get("channel_groups") or "").split(",")]
    samples = _unique_names([f"{c}" for c in ch])
    groups = {s: (labels[i] if i < len(labels) else "") for i, s in enumerate(samples)}
    agg = agg.rename(columns=dict(zip(ch, samples)))
    for s in samples:
        agg[s] = np.where(agg[s] > 0, agg[s], np.nan)
    if len(set(name_to_run)) > 1:
        job.flag("info", f"{len(name_to_run)} files were searched as one TMT plex: reporter intensities were summed across files "
                 "(fractions). Several separate plexes need a bridge channel and are not handled here.")
    if not any(groups.values()):
        job.flag("info", "TMT channels have no groups: set <b>channel_groups</b> (e.g. ctrl,ctrl,ctrl,trt,trt,trt,…) to test differences.")
    return agg, samples, groups, f"{S['tmt']} reporter-ion intensities at MS{S['tmt_level']} (summed per peptide)"


