def maxlfq(L: np.ndarray, min_ratios: int = 1) -> np.ndarray:
    """MaxLFQ (Cox et al. 2014) for one protein. L: peptides × samples, log2 intensity (NaN = missing).

    For every pair of samples, the median log-ratio over peptides seen in both; then the sample abundances
    x that best agree with all those ratios (least squares, solved separately for each group of samples that
    share peptides), scaled so that their summed intensity equals the protein's summed peptide intensity.
    A sample that shares no peptide with any other keeps its summed intensity.
    """
    S = L.shape[1]
    pres = np.isfinite(L)
    out = np.full(S, np.nan)
    have = pres.any(0)
    if not have.any():
        return out
    lin = np.where(pres, 2.0 ** np.where(pres, L, 0), 0.0)
    R = {}
    for j in range(S):
        for k in range(j + 1, S):
            both = pres[:, j] & pres[:, k]
            if both.sum() >= min_ratios:
                R[(j, k)] = float(np.median(L[both, j] - L[both, k]))
    # connected components of samples linked by ratios
    parent = list(range(S))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a
    for (j, k) in R:
        parent[find(j)] = find(k)
    comps: dict[int, list[int]] = {}
    for j in np.flatnonzero(have):
        comps.setdefault(find(j), []).append(int(j))
    for comp in comps.values():
        total = lin[:, comp].sum()
        if len(comp) == 1:
            out[comp[0]] = np.log2(total) if total > 0 else np.nan
            continue
        pos = {s: i for i, s in enumerate(comp)}
        pairs = [(j, k, r) for (j, k), r in R.items() if j in pos and k in pos]
        A = np.zeros((len(pairs), len(comp)))
        b = np.zeros(len(pairs))
        for row, (j, k, r) in enumerate(pairs):
            A[row, pos[j]], A[row, pos[k]], b[row] = 1, -1, r
        x = np.linalg.lstsq(A, b, rcond=None)[0]
        x += np.log2(total / np.sum(2.0 ** x))
        out[comp] = x
    return out


def rollup(pep: pd.DataFrame, samples: list[str], method: str = "maxlfq") -> pd.DataFrame:
    """pep: rows = peptides with columns 'protein' + sample intensities (linear, NaN missing) → log2 protein matrix."""
    rows, idx = [], []
    for prot, g in pep.groupby("protein", sort=False):
        M = g[samples].to_numpy(float)
        M = np.where(M > 0, M, np.nan)
        if method == "maxlfq":
            v = maxlfq(np.log2(M))
        elif method == "top3":
            v = np.full(len(samples), np.nan)
            for j in range(len(samples)):
                c = M[:, j][np.isfinite(M[:, j])]
                if len(c):
                    v[j] = np.log2(np.mean(np.sort(c)[-3:]))
        else:  # sum
            s = np.nansum(M, 0)
            v = np.where(np.isfinite(M).any(0), np.log2(np.where(s > 0, s, np.nan)), np.nan)
        rows.append(v)
        idx.append(prot)
    return pd.DataFrame(np.array(rows).reshape(len(idx), len(samples)), index=pd.Index(idx, name="protein"), columns=samples)


def impute_perseus(X: np.ndarray, width: float = 0.3, shift: float = 1.8, seed: int = 0):
    """Replace NaN per sample by draws from N(mean − shift·sd, (width·sd)²) of that sample's observed values."""
    rng = np.random.default_rng(seed)
    Y = X.copy()
    mask = ~np.isfinite(X)
    for j in range(X.shape[1]):
        obs = X[np.isfinite(X[:, j]), j]
        if len(obs) < 3 or not mask[:, j].any():
            continue
        mu, sd = obs.mean(), obs.std(ddof=1)
        Y[mask[:, j], j] = rng.normal(mu - shift * sd, width * sd, mask[:, j].sum())
    return Y, mask


