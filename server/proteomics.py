def read_fasta(path: Path) -> list[dict]:
    """[{id, header, seq, gene, desc}] — id is the first word of the header (what Sage reports)."""
    out, head, seq = [], None, []
    opener = open
    if str(path).endswith(".gz"):
        import gzip
        opener = gzip.open
    with opener(path, "rt", errors="replace") as fh:
        for line in fh:
            line = line.rstrip()
            if line.startswith(">"):
                if head is not None:
                    out.append(_fasta_entry(head, "".join(seq)))
                head, seq = line[1:], []
            elif line:
                seq.append(line.strip())
    if head is not None:
        out.append(_fasta_entry(head, "".join(seq)))
    return out


def _fasta_entry(head: str, seq: str) -> dict:
    pid = head.split()[0] if head.split() else head
    gn = re.search(r"\bGN=(\S+)", head)
    desc = head[len(pid):].strip()
    desc = re.split(r"\s(?:OS|OX|GN|PE|SV)=", desc)[0].strip()
    gene = gn.group(1) if gn else ""
    if not gene:  # no GN= (non-UniProt header): fall back to the entry name, e.g. sp|P02769|ALBU_BOVIN → ALBU
        parts = pid.split("|")
        gene = parts[2].split("_")[0] if len(parts) >= 3 else pid
    return {"id": pid, "header": head, "seq": seq.upper(), "gene": gene, "desc": desc}


def fetch_proteome(organism: str, progress=None) -> Path:
    """UniProt reviewed reference proteome for human / mouse / yeast / ecoli, cached in MB_HOME/cache."""
    key = str(organism or "").strip().lower()
    key = _ORG_ALIAS.get(key, key)
    if key not in PROTEOMES:
        raise UserFacingError(f"No built-in proteome for '{organism}'. Choose human, mouse, yeast or ecoli, "
                              "or give a protein FASTA file.")
    upid, latin = PROTEOMES[key]
    msio.CACHE.mkdir(parents=True, exist_ok=True)
    path = msio.CACHE / f"uniprot_{key}_{upid}_reviewed.fasta"
    if path.exists() and path.stat().st_size > 10000:
        return path
    url = ("https://rest.uniprot.org/uniprotkb/stream?format=fasta&query="
           + urllib.request.quote(f"(proteome:{upid}) AND (reviewed:true)"))
    tmp = path.with_suffix(".part")
    try:
        if progress:
            progress(f"Downloading the {latin} reference proteome from UniProt (first use only)")
        req = urllib.request.Request(url, headers={"User-Agent": "MassSpecBench/1.0"})
        with urllib.request.urlopen(req, timeout=120) as r, open(tmp, "wb") as f:
            shutil.copyfileobj(r, f, 1 << 20)
        head = tmp.read_bytes()[:1]
        if head != b">" or tmp.stat().st_size < 10000:
            raise ValueError("UniProt returned something that is not a FASTA file")
        tmp.replace(path)
    except Exception as e:  # noqa: BLE001
        tmp.unlink(missing_ok=True)
        raise UserFacingError(
            f"The {latin} protein database is downloaded from UniProt on first use, and the download failed "
            f"({type(e).__name__}: {str(e)[:120]}). Connect to the internet and re-run, or choose a protein FASTA "
            "file yourself (UniProt → Proteomes → your organism → Download → FASTA).") from e
    return path


