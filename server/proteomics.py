def _num(params, key, default, cast=float):
    v, src = resolve(params, key, default)
    try:
        return cast(v), src
    except (TypeError, ValueError):
        return cast(default), "default"


def _bool(params, key, default):
    v = params.get(key)
    if v is None or v == "":
        return bool(default), "default"
    if isinstance(v, str):
        return v.strip().lower() in ("1", "true", "yes", "on"), "user"
    return bool(v), "user"


def _short(x, n: int = 28) -> str:
    """Trim a long cell (e.g. a list of 15 histone genes) so tables stay readable; the CSV keeps the full text."""
    x = str(x)
    if ";" in x and len(x) > n:
        parts = x.split(";")
        x = parts[0] + f" +{len(parts) - 1}"
    return x if len(x) <= n else x[: n - 1] + "…"


def _strip(pep: str) -> str:
    """Plain sequence of a Sage peptide string: 'PEPM[+15.9949]C[+57.0215]K' → 'PEPMCK'."""
    return re.sub(r"[^A-Z]", "", re.sub(r"\[[^\]]*\]", "", str(pep)))


def _sheet_rows(files: list[Path], sheet) -> list[dict]:
    """One sheet row per file, matched by path, then by file name/stem; unmatched files get defaults."""
    if not sheet:
        return msio.match_sheet(files, None)
    rows = list(sheet)
    by = {}
    for r in rows:
        f = str(r.get("file") or "")
        if f:
            by.setdefault(f, r)
            by.setdefault(Path(f).name.lower(), r)
            by.setdefault(msio._stem(Path(f).name), r)
        if r.get("sample"):
            by.setdefault(msio._stem(str(r["sample"])), r)
    base = msio.match_sheet(files, None)
    out = []
    for f, b in zip(files, base):
        r = by.get(str(f)) or by.get(Path(f).name.lower()) or by.get(msio._stem(Path(f).name))
        if r:
            b = {**b, **{k: v for k, v in r.items() if v is not None}, "file": str(f)}
        b["group"] = str(b.get("group") or "").strip()
        b["type"] = str(b.get("type") or "sample").strip().lower() or "sample"
        b["sample"] = str(b.get("sample") or msio._stem(Path(f).name))
        out.append(b)
    return out


def _unique_names(names: list[str]) -> list[str]:
    seen, out = {}, []
    for n in names:
        n = re.sub(r"[^A-Za-z0-9_.+-]+", "_", n) or "run"
        k = seen.get(n, 0)
        seen[n] = k + 1
        out.append(n if k == 0 else f"{n}_{k + 1}")
    return out


def ms2_resolution(runs, max_spectra: int = 400):
    """Is MS2 high resolution (Orbitrap/TOF) or low (ion trap)? → ('high'|'low'|'unknown', evidence text).

    In a high-resolution fragment spectrum the 13C isotope peaks of a fragment sit exactly 1.0034 Da (or
    0.5017 Da at 2+) apart, so spacings between peaks pile up in a spike of a few mDa. At ion-trap
    resolution the same spacings scatter over ±0.1–0.3 Da. The fraction of near-1-Da spacings that fall
    within ±0.01 Da of the exact isotope spacing tells the two apart (≈0.1 for a flat, uninformative
    spread). Instrument metadata that names an ion-trap MS2 analyser is used as well.
    """
    idx = [(r, i) for r in runs for i in r.idx(2)]
    if not idx:
        return "unknown", "no MS2 spectra"
    rng = np.random.default_rng(0)
    pick = rng.choice(len(idx), min(max_spectra, len(idx)), replace=False)
    narrow = broad = 0
    npk = []
    for k in pick:
        r, i = idx[k]
        mz, it = r.spectrum(i)
        npk.append(len(mz))
        if len(mz) < 5:
            continue
        top = np.sort(mz[np.argsort(it)[-60:]])
        d = (top[None, :] - top[:, None]).ravel()
        d = d[d > 0.3]
        for sp, w in ((C13, 0.01), (C13 / 2, 0.005)):
            narrow += int((np.abs(d - sp) < w).sum())
            broad += int((np.abs(d - sp) < w * 10).sum())
    med_pk = float(np.median(npk)) if npk else 0
    inst = " ".join(str(r.meta.get("instrument", "")) for r in runs).lower()
    ratio = narrow / broad if broad else np.nan
    ev = f"isotope-spacing sharpness {ratio:.2f} (≈0.10 for low resolution, >0.25 for high), median {med_pk:.0f} peaks per MS2"
    if broad >= 40:
        return ("high" if ratio >= 0.22 else "low"), ev
    if any(k in inst for k in ("ltq", "velos", "ion trap", "amazon", "hct")) and "orbitrap" not in inst:
        return "low", f"instrument '{inst.strip()}' (ion trap); " + ev
    return "unknown", ev


