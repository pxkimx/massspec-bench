def trigamma_inverse(x):
    """Inverse of the trigamma function by Newton's method (limma's trigammaInverse, Smyth 2004)."""
    from scipy.special import polygamma
    x = np.atleast_1d(np.asarray(x, float))
    y = np.empty_like(x)
    big, small = x > 1e7, x < 1e-6
    y[big] = 1 / np.sqrt(x[big])
    y[small] = 1 / x[small]
    mid = ~(big | small)
    if mid.any():
        xm = x[mid]
        ym = 0.5 + 1 / xm
        for _ in range(50):
            tri = polygamma(1, ym)
            dif = tri * (1 - tri / xm) / polygamma(2, ym)
            ym = ym + dif
            if np.max(-dif / ym) < 1e-8:
                break
        y[mid] = ym
    return y


def fit_f_dist(s2, d):
    """Prior (d0, s0²) for sample variances s2 with d degrees of freedom — limma's fitFDist, method of moments
    on log-variances: E[log s²] and Var[log s²] of a scaled F distribution, solved for d0 with trigamma⁻¹."""
    from scipy.special import digamma, polygamma
    s2 = np.asarray(s2, float)
    d = np.asarray(d, float) * np.ones_like(s2)
    ok = np.isfinite(s2) & (s2 > 0) & np.isfinite(d) & (d > 0)
    s2, d = s2[ok], d[ok]
    n = len(s2)
    if n < 3:
        return np.inf, float(np.nanmedian(s2)) if n else np.nan
    z = np.log(s2)
    e = z - digamma(d / 2) + np.log(d / 2)
    emean = e.mean()
    evar = ((e - emean) ** 2).sum() / (n - 1) - polygamma(1, d / 2).mean()
    if evar > 0:
        d0 = float(2 * trigamma_inverse(evar)[0])
        s02 = float(np.exp(emean + digamma(d0 / 2) - np.log(d0 / 2)))
    else:
        d0, s02 = np.inf, float(np.exp(emean))
    return d0, s02


def moderated_t(X: np.ndarray, ia, ib, min_per_group: int = 2) -> pd.DataFrame:
    """Two-group limma-style test on log2 values (rows = proteins). Missing values are allowed per row.

    Per protein: group means, pooled residual variance s² on d = nA+nB−2 df. The prior d0, s0² is estimated
    from all proteins' s² (fit_f_dist); each protein's variance is shrunk to s̃² = (d0·s0² + d·s²)/(d0 + d)
    and the moderated t = Δ / (s̃·√(1/nA + 1/nB)) is referred to a t distribution with d + d0 df.
    """
    from scipy import stats
    A, B = X[:, ia], X[:, ib]
    na, nb = np.isfinite(A).sum(1), np.isfinite(B).sum(1)
    ok = (na >= min_per_group) & (nb >= min_per_group)
    import warnings
    with np.errstate(invalid="ignore", divide="ignore"), warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        ma, mb = np.nanmean(A, 1), np.nanmean(B, 1)
        ss = np.nansum((A - ma[:, None]) ** 2, 1) + np.nansum((B - mb[:, None]) ** 2, 1)
        d = (na + nb - 2).astype(float)
        s2 = np.where(ok & (d > 0), ss / np.where(d > 0, d, 1), np.nan)
    d0, s02 = fit_f_dist(s2[ok], d[ok])
    lfc = mb - ma
    unscaled = np.sqrt(1 / np.maximum(na, 1) + 1 / np.maximum(nb, 1))
    if np.isfinite(d0):
        post = (d0 * s02 + d * s2) / (d0 + d)
        df_tot = np.minimum(d + d0, np.nansum(d[ok]))
    else:
        post = np.full_like(s2, s02)
        df_tot = np.full_like(s2, np.nansum(d[ok]))
    with np.errstate(invalid="ignore", divide="ignore"):
        t = lfc / (np.sqrt(post) * unscaled)
        p = 2 * stats.t.sf(np.abs(t), df_tot)
        t_ord = lfc / (np.sqrt(s2) * unscaled)
    p = np.where(ok, p, np.nan)
    out = pd.DataFrame({"log2fc": np.where(ok, lfc, np.nan), "mean_a": ma, "mean_b": mb, "n_a": na, "n_b": nb,
                        "s2": s2, "s2_post": np.where(ok, post, np.nan), "t": np.where(ok, t, np.nan),
                        "t_ordinary": np.where(ok, t_ord, np.nan), "df": np.where(ok, df_tot, np.nan), "pvalue": p})
    out.attrs.update(d0=d0, s02=s02)
    return out


def welch(X, ia, ib):
    from scipy import stats
    A, B = X[:, ia], X[:, ib]
    with np.errstate(invalid="ignore", divide="ignore"):
        t, p = stats.ttest_ind(B, A, axis=1, equal_var=False, nan_policy="omit")
    t, p = np.asarray(t, float), np.asarray(p, float)
    na, nb = np.isfinite(A).sum(1), np.isfinite(B).sum(1)
    ok = (na >= 2) & (nb >= 2)
    ma, mb = np.nanmean(A, 1), np.nanmean(B, 1)
    return pd.DataFrame({"log2fc": np.where(ok, mb - ma, np.nan), "mean_a": ma, "mean_b": mb, "n_a": na, "n_b": nb,
                         "t": np.where(ok, t, np.nan), "pvalue": np.where(ok, p, np.nan)})


def bh(p):
    p = np.asarray(p, float)
    q = np.full_like(p, np.nan)
    ok = np.isfinite(p)
    pv = p[ok]
    n = len(pv)
    if not n:
        return q
    o = np.argsort(pv)
    r = pv[o] * n / np.arange(1, n + 1)
    r = np.minimum.accumulate(r[::-1])[::-1]
    qq = np.empty(n)
    qq[o] = np.minimum(r, 1)
    q[ok] = qq
    return q


